func TestArxivID(t *testing.T) {
	for in, want := range map[string]string{
		"https://arxiv.org/abs/1706.03762":              "1706.03762",
		"https://www.arxiv.org/abs/2401.04088v2":        "2401.04088v2",
		"http://arxiv.org/abs/cs/0112017":               "cs/0112017",
		"https://arxiv.org/abs/math.GT/0309136v1":       "math.GT/0309136v1",
		"https://arxiv.org/pdf/1706.03762":              "",
		"https://arxiv.org/abs/../html/x":               "",
		"https://arxiv.org.evil.example/abs/1706.03762": "",
		"https://example.com/abs/1706.03762":            "",
	} {
		if got := ArxivID(in); got != want {
			t.Errorf("ArxivID(%q) = %q, want %q", in, got, want)
		}
	}
}

