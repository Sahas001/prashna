func TestFromLaTeXML(t *testing.T) {
	base, _ := url.Parse("https://arxiv.org/html/2401.00001")
	art, err := FromLaTeXML([]byte(latexml), "text/html; charset=utf-8", base)
	if err != nil {
		t.Fatal(err)
	}
	if art.Title != "A Paper About Consensus" || art.Site != "arXiv" {
		t.Errorf("title %q site %q", art.Title, art.Site)
	}
	for _, want := range []string{
		`<div class="p-abstract"><h6>Abstract</h6><p>We study agreement`,
		`<h2>1 Introduction</h2>`,
		`agree<sup>1</sup> on a value`, // the footnote's text has left the sentence
		`<math alttext="v &lt; n" display="inline"><semantics><mrow><mi mathvariant="normal">v</mi><mo>&lt;</mo><mi>n</mi></mrow></semantics></math>`,
		`Lamport [1]`, // in-page citation link: text only
		`<a href="https://example.org/paper" target="_blank" rel="noopener noreferrer">other work</a>`,
		`<div class="p-eq"><math display="block" alttext="f"><mfrac><mi>a</mi><mi>b</mi></mfrac><mtext></mtext></math><small class="p-eqno">(1)</small></div>`,
		`<img src="https://arxiv.org/html/2401.00001v1/x1.png" alt="" loading="lazy" referrerpolicy="no-referrer">`,
		`<div class="p-notes"><h2>Notes</h2><ol><li>Even when some of them <em>fail</em>.</li></ol></div><h2>References</h2>`,
		`<ul class="p-refs"><li>[1]L. Lamport. The part-time parliament.</li></ul>`,
	} {
		if !strings.Contains(strings.ReplaceAll(art.HTML, "\n", ""), want) {
			t.Errorf("output lacks %q", want)
		}
	}
	for _, bad := range []string{"A. Author", "Equal contribution", "Site chrome", "track()", "Generated by", "1 Intro</li>", `\foo`,
		"onclick", "onerror", "javascript:", "<script", "alert(", "maction", "annotation", "<table", "ltx_", "thanks:"} {
		if strings.Contains(art.HTML, bad) {
			t.Errorf("output contains %q", bad)
		}
	}
	// What we emit must survive the browser's own parse unchanged: no
	// element may appear that the sanitizer didn't write.
	doc, err := html.Parse(strings.NewReader(art.HTML))
	if err != nil {
		t.Fatal(err)
	}
	again, _ := Sanitize(doc, nil)
	if strings.Count(again, "<") != strings.Count(art.HTML, "<") {
		t.Errorf("re-parsing changed the markup:\n%s\n---\n%s", art.HTML, again)
	}
}

func TestExtractArxiv(t *testing.T) {
	mux := http.NewServeMux()
	page := func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Write([]byte(latexml))
	}
	mux.HandleFunc("/html/2401.00001", page)                                 // on arXiv itself
	mux.HandleFunc("/ar5iv/1706.03762", page)                                // only in the archive
	mux.HandleFunc("/ar5iv/", func(w http.ResponseWriter, r *http.Request) { // the archive's "don't have it"
		http.Redirect(w, r, "/abs/"+strings.TrimPrefix(r.URL.Path, "/ar5iv/"), http.StatusFound)
	})
	mux.HandleFunc("/abs/", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "text/html")
		w.Write([]byte("<html><body><p>Abstract page</p></body></html>"))
	})
	srv := httptest.NewServer(mux)
	defer srv.Close()
	e := &Extractor{HTTP: srv.Client(), ArxivHTML: []string{srv.URL + "/html/", srv.URL + "/ar5iv/"}}
	ctx := context.Background()

	for _, id := range []string{"2401.00001", "1706.03762"} {
		art, err := e.Extract(ctx, "https://arxiv.org/abs/"+id)
		if err != nil || art.Title != "A Paper About Consensus" {
			t.Errorf("%s: %q %v", id, art.Title, err)
		}
	}
	if _, err := e.Extract(ctx, "https://arxiv.org/abs/2611.99999"); !errors.Is(err, ErrNoHTML) {
		t.Errorf("no web version: err = %v", err)
	}
}
